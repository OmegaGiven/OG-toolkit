#[derive(Debug, Clone)]
pub struct StartupExecEntry {
    pub line_index: usize,
    pub original_line: String,
    pub always: bool,
    pub command: String,
    pub enabled: bool,
}

fn strip_leading_hash(line: &str) -> String {
    let trimmed = line.trim_start();
    let indent = &line[..line.len() - trimmed.len()];
    format!("{}{}", indent, trimmed.trim_start_matches('#').trim_start())
}

fn add_leading_hash(line: &str) -> String {
    let trimmed = line.trim_start();
    let indent = &line[..line.len() - trimmed.len()];
    format!("{indent}# {trimmed}")
}

/// Single-line `exec`/`exec_always` startup commands from the sway config —
/// the toggleable subset of sway's own autostart list. Deliberately skips:
/// brace-block form (`exec_always { ... }`), line-continuations (trailing
/// `\`), and anything inside a nested block — those aren't safe to comment
/// out one line at a time without breaking the surrounding statement.
pub fn get_startup_execs() -> Vec<StartupExecEntry> {
    let config_path = format!("{}/.config/sway/config", home());
    let Ok(content) = std::fs::read_to_string(&config_path) else { return Vec::new() };

    let mut out = Vec::new();
    let mut depth: i32 = 0;
    for (idx, line) in content.lines().enumerate() {
        let trimmed = line.trim();
        let (is_disabled, working) = match trimmed.strip_prefix('#') {
            Some(rest) => (true, rest.trim_start()),
            None => (false, trimmed),
        };

        if is_disabled {
            // A plain comment must not affect brace depth; only continue
            // parsing it as a possible disabled exec line below.
        } else if trimmed.starts_with('}') {
            depth -= 1;
        }

        if depth == 0 && !trimmed.ends_with('\\') && !working.ends_with('{') {
            let (always, rest) = if let Some(r) = working.strip_prefix("exec_always ") {
                (true, r)
            } else if let Some(r) = working.strip_prefix("exec ") {
                (false, r)
            } else {
                (false, "")
            };
            let command = rest.trim();
            if !command.is_empty() {
                out.push(StartupExecEntry {
                    line_index: idx,
                    original_line: line.to_string(),
                    always,
                    command: command.to_string(),
                    enabled: !is_disabled,
                });
            }
        }

        if !is_disabled {
            if trimmed.ends_with('{') {
                depth += 1;
            }
        }
    }
    out
}

/// Comments or uncomments one specific line by index, verifying it still
/// matches `expected` first (defensive against the file having changed
/// since the list was loaded) — returns the new line text on success.
pub fn toggle_startup_exec(line_index: usize, expected: &str, enable: bool) -> Option<String> {
    let config_path = format!("{}/.config/sway/config", home());
    let content = std::fs::read_to_string(&config_path).ok()?;
    let mut lines: Vec<String> = content.lines().map(str::to_string).collect();

    if lines.get(line_index).map(String::as_str) != Some(expected) {
        return None;
    }
    let new_line = if enable { strip_leading_hash(expected) } else { add_leading_hash(expected) };
    lines[line_index] = new_line.clone();
    std::fs::write(&config_path, lines.join("\n") + "\n").ok()?;
    reload();
    Some(new_line)
}

