use std::process::Command;
use crate::config::Config;

fn home() -> String {
    std::env::var("HOME").unwrap_or_default()
}

fn darken(hex: &str, factor: f32) -> String {
    let h = hex.trim_start_matches('#');
    if h.len() < 6 { return hex.to_string(); }
    let r = u8::from_str_radix(&h[0..2], 16).unwrap_or(0);
    let g = u8::from_str_radix(&h[2..4], 16).unwrap_or(0);
    let b = u8::from_str_radix(&h[4..6], 16).unwrap_or(0);
    format!("#{:02x}{:02x}{:02x}",
        (r as f32 * factor) as u8,
        (g as f32 * factor) as u8,
        (b as f32 * factor) as u8)
}

fn hex_to_rgba(hex: &str, alpha: f32) -> String {
    let h = hex.trim_start_matches('#');
    if h.len() < 6 { return format!("rgba(128,128,128,{alpha})"); }
    let r = u8::from_str_radix(&h[0..2], 16).unwrap_or(128);
    let g = u8::from_str_radix(&h[2..4], 16).unwrap_or(128);
    let b = u8::from_str_radix(&h[4..6], 16).unwrap_or(128);
    format!("rgba({r},{g},{b},{alpha})")
}

/// Full theme apply: waybar CSS + sway client colors + layout + reload
pub fn apply_theme(config: &Config) {
    write_waybar_theme(config);
    write_wofi_theme(config);
    update_sway_client_colors(config);
    update_sway_layout(config);
    apply_wallpaper(config);
    // swaymsg reload restarts waybar via exec_always in sway config
    reload();
    // Reload only sets defaults for new workspaces/windows — push the new
    // gaps and borders onto everything that already exists.
    set_gaps_inner(config.gaps_inner);
    set_gaps_outer(config.gaps_outer);
    set_border_width(config.border_width);
    run_power_apply();
}

/// Persist gaps + border width into the sway config file.
fn update_sway_layout(config: &Config) {
    let replacements: [(&str, String); 4] = [
        ("gaps inner", format!("gaps inner {}", config.gaps_inner)),
        ("gaps outer", format!("gaps outer {}", config.gaps_outer)),
        ("default_border pixel", format!("default_border pixel {}", config.border_width)),
        ("default_floating_border pixel", format!("default_floating_border pixel {}", config.border_width)),
    ];

    let config_path = format!("{}/.config/sway/config", home());
    let content = match std::fs::read_to_string(&config_path) {
        Ok(c) => c,
        Err(_) => return,
    };

    let mut lines: Vec<String> = content.lines().map(|l| l.to_string()).collect();
    let mut handled = [false; 4];

    for line in &mut lines {
        let trimmed = line.trim_start().to_string();
        for (i, (key, new_line)) in replacements.iter().enumerate() {
            if trimmed.starts_with(key) && !handled[i] {
                *line = new_line.clone();
                handled[i] = true;
            }
        }
    }
    for (i, (_, new_line)) in replacements.iter().enumerate() {
        if !handled[i] {
            lines.push(new_line.clone());
        }
    }

    let _ = std::fs::write(&config_path, lines.join("\n") + "\n");
}

fn write_waybar_theme(config: &Config) {
    let bar_bg  = &config.bar_bg;
    let text    = &config.bar_text;
    let accent  = &config.accent;
    let urgent  = &config.urgent_color;
    let inactive = &config.inactive_color;
    let sec_bg  = &config.sec_bg;

    let css = format!(
r#"/* Auto-generated by settings-manager — do not edit */
window#waybar,
window#waybar > box,
window#waybar > box > box {{
  background-color: {bar_bg};
  color: {text};
}}
#cpu, #memory, #pulseaudio, #clock {{
  background-color: {sec_bg};
  border: 1px solid {inactive};
}}
#workspaces button.focused {{
  color: {accent};
  border-top: 1px solid {accent};
  border-bottom: 1px solid {accent};
  border-left: 3px solid {accent};
  border-right: 3px solid {accent};
}}
#workspaces button:hover {{
  color: {inactive};
  background-color: rgba(255,255,255,0.05);
}}
#bluetooth.on,
#bluetooth.discoverable,
#bluetooth.pairable {{
  color: {accent};
}}
#bluetooth.connected {{
  color: {accent};
  border-left: 2px solid {accent};
}}
#network.wifi,
#network.ethernet {{
  color: {accent};
}}
#cpu.warning, #memory.warning {{
  color: {accent};
  border-color: {accent};
}}
#cpu.critical, #memory.critical {{
  color: {urgent};
  border-color: {urgent};
}}
"#);

    let overrides_path = format!("{}/.config/waybar/theme-overrides.css", home());
    let _ = std::fs::write(&overrides_path, css);

    // One-time: prepend @import to style.css if not already there
    let style_path = format!("{}/.config/waybar/style.css", home());
    if let Ok(content) = std::fs::read_to_string(&style_path) {
        if !content.contains("theme-overrides.css") {
            let patched = format!("@import \"theme-overrides.css\";\n\n{}", content);
            let _ = std::fs::write(&style_path, patched);
        }
    }
}

/// wofi (used for app search, clipboard history, and notification history)
/// otherwise renders with the bare default GTK theme — jarring against
/// everything else here. wofi auto-loads `style.css` from its own config
/// dir with no extra wiring needed, same way waybar's does.
fn write_wofi_theme(config: &Config) {
    let bar_bg = &config.bar_bg;
    let sec_bg = &config.sec_bg;
    let text = &config.bar_text;
    let accent = &config.accent;
    let border = hex_to_rgba(&config.bar_text, 0.22);
    let selection_bg = hex_to_rgba(&config.accent, 0.25);
    let radius = config.corner_radius.max(4.0);

    let css = format!(
r#"/* Auto-generated by settings-manager — do not edit */
window#window {{
  background-color: {bar_bg};
  border: 1px solid {border};
  border-radius: {radius}px;
}}
#input {{
  background-color: {sec_bg};
  color: {text};
  border: 1px solid {border};
  border-radius: {radius}px;
  margin: 6px;
  padding: 6px 10px;
}}
#outer-box {{
  background-color: {bar_bg};
  border-radius: {radius}px;
  margin: 4px;
}}
#scroll {{
  margin: 4px;
}}
#inner-box {{
  background-color: {bar_bg};
}}
#text {{
  color: {text};
}}
#entry {{
  padding: 6px;
  border-radius: {radius}px;
}}
#entry:selected {{
  background-color: {selection_bg};
}}
#entry:selected #text {{
  color: {accent};
}}
"#);

    let dir = format!("{}/.config/wofi", home());
    let _ = std::fs::create_dir_all(&dir);
    let _ = std::fs::write(format!("{dir}/style.css"), css);
}

fn update_sway_client_colors(config: &Config) {
    let accent   = &config.accent;
    let bar_bg   = &config.bar_bg;
    let bar_text = &config.bar_text;
    let sec_bg   = &config.sec_bg;
    let inactive = &config.inactive_color;
    let urgent   = &config.urgent_color;

    let dark_inactive = darken(inactive, 0.6);
    let dark_urgent   = darken(urgent, 0.4);

    // format: client.X  border  bg  text  indicator  child_border
    let replacements = [
        ("client.focused",
         format!("client.focused          {} {} {} {} {}", accent, sec_bg, bar_text, accent, accent)),
        ("client.focused_inactive",
         format!("client.focused_inactive {} {} {} {} {}", inactive, bar_bg, bar_text, inactive, inactive)),
        ("client.unfocused",
         format!("client.unfocused        {} {} {} {} {}", dark_inactive, bar_bg, bar_text, bar_bg, dark_inactive)),
        ("client.urgent",
         format!("client.urgent           {} {} {} {} {}", urgent, dark_urgent, bar_text, urgent, urgent)),
    ];

    let config_path = format!("{}/.config/sway/config", home());
    let content = match std::fs::read_to_string(&config_path) {
        Ok(c) => c,
        Err(_) => return,
    };

    let mut lines: Vec<String> = content.lines().map(|l| l.to_string()).collect();
    let mut handled = [false; 4];

    for line in &mut lines {
        let trimmed = line.trim_start().to_string();
        for (i, (key, new_line)) in replacements.iter().enumerate() {
            if trimmed.starts_with(key) {
                *line = new_line.clone();
                handled[i] = true;
            }
        }
    }
    // Append any that weren't found
    for (i, (_, new_line)) in replacements.iter().enumerate() {
        if !handled[i] {
            lines.push(new_line.clone());
        }
    }

    let _ = std::fs::write(&config_path, lines.join("\n") + "\n");
}

fn is_vertical(pos: &str) -> bool {
    pos == "left" || pos == "right"
}

/// Patch waybar's own config file for a new screen edge, thickness, or
/// clock setup — position and layer-orientation both change: bar thickness
/// (width vs height) and every module format that stacks its label
/// vertically on a `left`/`right` bar need to become single-line when the
/// bar goes `top`/`bottom`, and back again when it returns to a vertical
/// edge. SIGUSR2 reload can't apply any of this, so this kills and
/// relaunches the process instead.
pub fn set_waybar_layout(config: &Config) {
    let pos = config.waybar_position.as_str();
    let thickness = config.waybar_thickness;

    let config_path = format!("{}/.config/waybar/config", home());
    let Ok(content) = std::fs::read_to_string(&config_path) else { return };
    let Ok(mut root): Result<serde_json::Value, _> = serde_json::from_str(&content) else { return };
    let Some(map) = root.as_object_mut() else { return };

    map.insert("position".into(), serde_json::Value::String(pos.to_string()));

    if is_vertical(pos) {
        map.remove("height");
        map.insert("width".into(), serde_json::json!(thickness));
    } else {
        map.remove("width");
        map.insert("height".into(), serde_json::json!(thickness));
    }

    let vertical = is_vertical(pos);

    if let Some(ws) = map.get_mut("sway/workspaces").and_then(|v| v.as_object_mut()) {
        ws.insert("format".into(), serde_json::json!(if vertical {
            "<span size='xx-large'>{name}</span>\n<span size='x-small'>─────</span>\n{windows}"
        } else {
            "<span size='large'>{name}</span> <span size='x-small'>│</span> {windows}"
        }));
        ws.insert("format-window-separator".into(), serde_json::json!(if vertical { "\n" } else { " " }));
        if let Some(rewrite) = ws.get_mut("window-rewrite").and_then(|v| v.as_object_mut()) {
            for v in rewrite.values_mut() {
                if let Some(s) = v.as_str() {
                    let swapped = if vertical {
                        s.replace("size='large'", "size='xx-large'")
                    } else {
                        s.replace("size='xx-large'", "size='large'")
                    };
                    *v = serde_json::Value::String(swapped);
                }
            }
        }
    }

    // On a vertical bar, "10:30 PM" on one line is wider than the column —
    // wrap AM/PM to its own line instead of widening the whole bar. On a
    // horizontal bar there's no such constraint, so it stays inline there.
    let vertical_time_part = if config.clock_12h { "%I:%M\n%p" } else { "%H:%M" };
    let horizontal_time_part = if config.clock_12h { "%I:%M %p" } else { "%H:%M" };
    let clock_format: String = if vertical {
        format!("{{:%Z\n%m|%d\n{vertical_time_part}}}")
    } else {
        format!("{{:%Z %m/%d {horizontal_time_part}}}")
    };
    let clock_tooltip: String = if config.clock_12h {
        "{:%Y-%m-%d %I:%M:%S %p}".to_string()
    } else {
        "{:%Y-%m-%d %H:%M:%S}".to_string()
    };

    if let Some(clock) = map.get_mut("clock").and_then(|v| v.as_object_mut()) {
        clock.insert("format".into(), serde_json::json!(clock_format));
        clock.insert("tooltip-format".into(), serde_json::json!(clock_tooltip));
        if config.clock_timezone.is_empty() {
            clock.remove("timezone");
        } else {
            clock.insert("timezone".into(), serde_json::json!(config.clock_timezone));
        }
    }

    // Drop any previously-generated extra clock widgets, then re-add one per
    // configured clock — keeps repeated edits idempotent instead of piling
    // up stale `clock#N` blocks. Placement in the module lists is owned by
    // config.modules_left/center/right (see below), not generated here.
    let stale_ids: Vec<String> = map.keys()
        .filter(|k| k.starts_with("clock#"))
        .cloned()
        .collect();
    for id in &stale_ids {
        map.remove(id);
    }
    for cc in &config.extra_clocks {
        map.insert(cc.module_id(), serde_json::json!({
            "format": clock_format,
            "tooltip-format": clock_tooltip,
            "timezone": cc.timezone,
        }));
    }

    // Module arrangement (drag-arrange screen) is the single source of
    // truth once seeded; an empty list here means "never seeded / user
    // hasn't touched it", so leave whatever's already in the bar file alone
    // rather than blanking a section out.
    for (section, modules) in [
        ("modules-left", &config.modules_left),
        ("modules-center", &config.modules_center),
        ("modules-right", &config.modules_right),
    ] {
        if !modules.is_empty() {
            map.insert(section.into(), serde_json::json!(modules));
        }
    }

    if let Some(cpu) = map.get_mut("cpu").and_then(|v| v.as_object_mut()) {
        cpu.insert("format".into(), serde_json::json!(if vertical { "CPU\n{usage}%" } else { "CPU {usage}%" }));
    }

    if let Some(mem) = map.get_mut("memory").and_then(|v| v.as_object_mut()) {
        mem.insert("format".into(), serde_json::json!(if vertical { "RAM\n{percentage}%" } else { "RAM {percentage}%" }));
    }

    if let Some(net) = map.get_mut("network").and_then(|v| v.as_object_mut()) {
        net.insert("format-wifi".into(), serde_json::json!(if vertical { "󰖩\n{essid}" } else { "󰖩 {essid}" }));
    }

    if let Some(pulse) = map.get_mut("pulseaudio").and_then(|v| v.as_object_mut()) {
        pulse.insert("format".into(), serde_json::json!(if vertical { "󰕾\n{volume}%" } else { "󰕾 {volume}%" }));
        pulse.insert("format-muted".into(), serde_json::json!(if vertical { "󰖁\nMUTE" } else { "󰖁 MUTE" }));
    }

    let Ok(pretty) = serde_json::to_string_pretty(&root) else { return };
    let _ = std::fs::write(&config_path, pretty + "\n");

    set_clock_css_padding(vertical);
    set_module_thickness_css(thickness);

    let _ = Command::new("pkill").arg("waybar").output();
    let _ = Command::new("waybar").spawn();
}

/// Every module's `min-width`/`min-height: Npx;` in style.css hardcodes the
/// module's cross-axis size — CSS min-size wins over whatever `width`/
/// `height` we write into waybar's own JSON config, so without this the
/// thickness setting silently does nothing once it's below the hardcoded
/// value (and can't grow past it either). Value-agnostic: matches any
/// current `Npx` so repeated thickness changes stay idempotent, and
/// deliberately excludes the `* { min-height: 0; }` reset since that value
/// has no `px` suffix.
fn set_module_thickness_css(thickness: i32) {
    let style_path = format!("{}/.config/waybar/style.css", home());
    let Ok(content) = std::fs::read_to_string(&style_path) else { return };

    let lines: Vec<String> = content.lines().map(|l| {
        let trimmed = l.trim();
        let prop = if trimmed.starts_with("min-width:") {
            Some("min-width")
        } else if trimmed.starts_with("min-height:") {
            Some("min-height")
        } else {
            None
        };
        if let Some(prop) = prop {
            if trimmed.ends_with("px;") {
                let indent = &l[..l.len() - l.trim_start().len()];
                return format!("{indent}{prop}: {thickness}px;");
            }
        }
        l.to_string()
    }).collect();

    let _ = std::fs::write(&style_path, lines.join("\n") + "\n");
}

/// The clock's vertical layout (`left`/`right` bar) needs top-only padding
/// since the format string is already 3 lines tall; the horizontal layout
/// (`top`/`bottom` bar) is single-line and was sitting flush against its
/// own border on the left/right, so it needs side padding instead.
fn set_clock_css_padding(vertical: bool) {
    let style_path = format!("{}/.config/waybar/style.css", home());
    let Ok(content) = std::fs::read_to_string(&style_path) else { return };

    let new_padding = if vertical { "4px 0px 0px 0px" } else { "4px 10px" };
    let mut in_clock = false;
    let mut patched = false;
    let lines: Vec<String> = content.lines().map(|l| {
        let trimmed = l.trim();
        if trimmed == "#clock {" {
            in_clock = true;
        } else if in_clock && trimmed == "}" {
            in_clock = false;
        } else if in_clock && trimmed.starts_with("padding:") {
            patched = true;
            let indent = &l[..l.len() - l.trim_start().len()];
            return format!("{indent}padding: {new_padding};");
        }
        l.to_string()
    }).collect();

    if !patched {
        return;
    }
    let _ = std::fs::write(&style_path, lines.join("\n") + "\n");
}

