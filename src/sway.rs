#[derive(Debug, Clone)]
pub struct SystemdServiceInfo {
    pub unit: String,
    pub enabled: bool,
}

/// User-level systemd services that are meaningfully toggleable — i.e.
/// `systemctl --user list-unit-files` reports them as plainly `enabled` or
/// `disabled` (not `static`/`alias`/`generated`/`transient`/`indirect`,
/// which can't be flipped this way) and aren't instance templates like
/// `foo@.service`, which need an instance name to mean anything.
pub fn get_systemd_user_services() -> Vec<SystemdServiceInfo> {
    let output = match Command::new("systemctl")
        .args(["--user", "list-unit-files", "--type=service", "--no-legend"])
        .output()
    {
        Ok(o) => o,
        Err(_) => return Vec::new(),
    };
    let text = String::from_utf8_lossy(&output.stdout);
    let mut services: Vec<SystemdServiceInfo> = text.lines()
        .filter_map(|line| {
            let mut cols = line.split_whitespace();
            let unit = cols.next()?.to_string();
            let state = cols.next()?;
            if unit.contains("@.service") {
                return None;
            }
            match state {
                "enabled" => Some(SystemdServiceInfo { unit, enabled: true }),
                "disabled" => Some(SystemdServiceInfo { unit, enabled: false }),
                _ => None,
            }
        })
        .collect();
    services.sort_by(|a, b| a.unit.cmp(&b.unit));
    services
}

pub fn set_systemd_service_enabled(unit: &str, enabled: bool) {
    let action = if enabled { "enable" } else { "disable" };
    let _ = Command::new("systemctl")
        .args(["--user", action, unit])
        .output();
}

/// System-level (not `--user`) services — things like tailscaled,
/// NetworkManager, etc. that run as root and aren't visible to the
/// per-session `--user` service manager at all.
pub fn get_system_services() -> Vec<SystemdServiceInfo> {
    let output = match Command::new("systemctl")
        .args(["list-unit-files", "--type=service", "--no-legend"])
        .output()
    {
        Ok(o) => o,
        Err(_) => return Vec::new(),
    };
    let text = String::from_utf8_lossy(&output.stdout);
    let mut services: Vec<SystemdServiceInfo> = text.lines()
        .filter_map(|line| {
            let mut cols = line.split_whitespace();
            let unit = cols.next()?.to_string();
            let state = cols.next()?;
            if unit.contains("@.service") {
                return None;
            }
            match state {
                "enabled" => Some(SystemdServiceInfo { unit, enabled: true }),
                "disabled" => Some(SystemdServiceInfo { unit, enabled: false }),
                _ => None,
            }
        })
        .collect();
    services.sort_by(|a, b| a.unit.cmp(&b.unit));
    services
}

