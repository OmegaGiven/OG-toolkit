#[derive(Debug, Clone, Default)]
pub struct WifiStatus {
    pub powered: bool,
    pub connected_ssid: Option<String>,
    pub ip: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq)]
enum NetworkBackend {
    NetworkManager,
    Iwd,
    None,
}

/// This machine runs iwd, so that's the only backend actually exercised
/// against a real system. NetworkManager is by far the more common default
/// on most other distros (Ubuntu, Fedora, Debian, etc.), so it's supported
/// too — built carefully against `nmcli`'s documented terse (`-t`) output
/// format, but unverified against a live NetworkManager install.
fn detect_network_backend() -> NetworkBackend {
    // `nmcli general status` only succeeds if the NetworkManager daemon is
    // actually running, not just installed — prefer it when active since
    // it's the more common default.
    if Command::new("nmcli").args(["-t", "general", "status"]).output()
        .is_ok_and(|o| o.status.success())
    {
        return NetworkBackend::NetworkManager;
    }
    if Command::new("which").arg("iwctl").output().is_ok_and(|o| o.status.success()) {
        return NetworkBackend::Iwd;
    }
    NetworkBackend::None
}

/// Splits an nmcli `-t` (terse) line on unescaped `:` — nmcli backslash-
/// escapes literal `:` and `\` inside field values in this mode.
fn parse_nmcli_terse_line(line: &str) -> Vec<String> {
    let mut fields = Vec::new();
    let mut current = String::new();
    let mut chars = line.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\\' {
            if let Some(next) = chars.next() {
                current.push(next);
                continue;
            }
        }
        if c == ':' {
            fields.push(std::mem::take(&mut current));
        } else {
            current.push(c);
        }
    }
    fields.push(current);
    fields
}

fn wifi_iface() -> Option<String> {
    let out = run_output("iwctl", &["device", "list"]);
    for line in strip_ansi(&out).lines() {
        let cols = split_table_columns(line);
        if cols.len() >= 4 && cols[0] != "Name" {
            return Some(cols[0].clone());
        }
    }
    None
}

fn wifi_iface_nm() -> Option<String> {
    let out = run_output("nmcli", &["-t", "-f", "DEVICE,TYPE", "device", "status"]);
    for line in out.lines() {
        let cols = parse_nmcli_terse_line(line);
        if cols.len() >= 2 && cols[1] == "wifi" {
            return Some(cols[0].clone());
        }
    }
    None
}

fn interface_ip(iface: &str) -> Option<String> {
    let addr = run_output("ip", &["-4", "-o", "addr", "show", iface]);
    addr.split_whitespace()
        .position(|w| w == "inet")
        .and_then(|i| addr.split_whitespace().nth(i + 1))
        .map(|s| s.split('/').next().unwrap_or(s).to_string())
}

pub fn get_wifi_status() -> WifiStatus {
    let rfkill = run_output("rfkill", &["list", "wifi"]);
    let powered = !rfkill.contains("Soft blocked: yes") && !rfkill.is_empty();

    match detect_network_backend() {
        NetworkBackend::NetworkManager => {
            let Some(iface) = wifi_iface_nm() else { return WifiStatus { powered, ..Default::default() } };
            let out = run_output("nmcli", &["-t", "-f", "DEVICE,STATE,CONNECTION", "device", "status"]);
            let connected_ssid = out.lines()
                .map(parse_nmcli_terse_line)
                .find(|cols| cols.len() >= 3 && cols[0] == iface && cols[1] == "connected")
                .map(|cols| cols[2].clone())
                .filter(|s| !s.is_empty());
            let ip = connected_ssid.as_ref().and_then(|_| interface_ip(&iface));
            WifiStatus { powered, connected_ssid, ip }
        }
        NetworkBackend::Iwd => {
            let Some(iface) = wifi_iface() else { return WifiStatus { powered, ..Default::default() } };
            let show = strip_ansi(&run_output("iwctl", &["station", &iface, "show"]));
            let connected_ssid = show.lines()
                .find(|l| l.trim_start().starts_with("Connected network"))
                .and_then(|l| l.splitn(2, "Connected network").nth(1))
                .map(|s| s.trim().to_string())
                .filter(|s| !s.is_empty());
            let ip = connected_ssid.as_ref().and_then(|_| interface_ip(&iface));
            WifiStatus { powered, connected_ssid, ip }
        }
        NetworkBackend::None => WifiStatus { powered, ..Default::default() },
    }
}

