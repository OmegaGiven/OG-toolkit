pub fn get_outputs() -> Vec<String> {
    let out = Command::new("swaymsg")
        .args(["-t", "get_outputs"])
        .output()
        .ok();
    out.and_then(|o| {
        let s = String::from_utf8_lossy(&o.stdout).to_string();
        let v: serde_json::Value = serde_json::from_str(&s).ok()?;
        Some(
            v.as_array()?
                .iter()
                .filter_map(|o| o["name"].as_str().map(|s| s.to_string()))
                .collect(),
        )
    })
    .unwrap_or_default()
}

#[derive(Debug, Clone)]
pub struct MonitorInfo {
    pub name: String,
    pub make: String,
    pub model: String,
    pub x: i32,
    pub y: i32,
    pub width: i32,
    pub height: i32,
    pub current_mode: String,
    pub modes: Vec<String>,
    pub active: bool,
}

pub fn get_monitor_info() -> Vec<MonitorInfo> {
    let output = match Command::new("swaymsg").args(["-t", "get_outputs"]).output() {
        Ok(o) => o,
        Err(_) => return Vec::new(),
    };
    let json_str = String::from_utf8_lossy(&output.stdout);
    let v: serde_json::Value = match serde_json::from_str(&json_str) {
        Ok(v) => v,
        Err(_) => return Vec::new(),
    };
    let arr = match v.as_array() {
        Some(a) => a,
        None => return Vec::new(),
    };

    arr.iter().map(|o| {
        let name = o["name"].as_str().unwrap_or("").to_string();
        let make = o["make"].as_str().unwrap_or("Unknown").to_string();
        let model = o["model"].as_str().unwrap_or("Unknown").to_string();
        let x = o["rect"]["x"].as_i64().unwrap_or(0) as i32;
        let y = o["rect"]["y"].as_i64().unwrap_or(0) as i32;
        let width = o["rect"]["width"].as_i64().unwrap_or(1920) as i32;
        let height = o["rect"]["height"].as_i64().unwrap_or(1080) as i32;
        let active = o["active"].as_bool().unwrap_or(false);

        let cm = &o["current_mode"];
        let cw = cm["width"].as_i64().unwrap_or(0);
        let ch = cm["height"].as_i64().unwrap_or(0);
        let cr = cm["refresh"].as_i64().unwrap_or(0);
        let current_mode = format!("{}x{}@{}Hz", cw, ch, cr / 1000);

        let mut modes: Vec<String> = o["modes"].as_array()
            .map(|modes| {
                modes.iter().map(|m| {
                    let w = m["width"].as_i64().unwrap_or(0);
                    let h = m["height"].as_i64().unwrap_or(0);
                    let r = m["refresh"].as_i64().unwrap_or(0);
                    format!("{}x{}@{}Hz", w, h, r / 1000)
                }).collect()
            })
            .unwrap_or_default();
        modes.dedup();

        MonitorInfo { name, make, model, x, y, width, height, current_mode, modes, active }
    }).collect()
}

