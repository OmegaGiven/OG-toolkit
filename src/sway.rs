// ── Brightness ───────────────────────────────────────────────────────────

/// True if a real screen backlight device exists (laptop panel/eDP). False
/// on desktops with external monitors — those have no /sys/class/backlight
/// entry and rely on the monitor's own OSD/DDC controls instead, so the
/// brightness feature stays wired but should show as unavailable there.
pub fn has_backlight() -> bool {
    std::fs::read_dir("/sys/class/backlight")
        .map(|mut d| d.next().is_some())
        .unwrap_or(false)
}

pub fn get_brightness_percent() -> Option<u32> {
    let cur: u32 = Command::new("brightnessctl")
        .args(["--class=backlight", "get"])
        .output()
        .ok()
        .and_then(|o| String::from_utf8_lossy(&o.stdout).trim().parse().ok())?;
    let max: u32 = Command::new("brightnessctl")
        .args(["--class=backlight", "max"])
        .output()
        .ok()
        .and_then(|o| String::from_utf8_lossy(&o.stdout).trim().parse().ok())?;
    if max == 0 { return None; }
    Some(((cur as f64 / max as f64) * 100.0).round() as u32)
}

pub fn set_brightness_percent(pct: u32) {
    let _ = Command::new("brightnessctl")
        .args(["--class=backlight", "set", &format!("{pct}%")])
        .output();
}

// ── Wallpaper ────────────────────────────────────────────────────────────

/// Non-recursive scan of the usual wallpaper spots for pick_list options.
pub fn scan_wallpapers() -> Vec<String> {
    let dirs = [
        format!("{}/desktop backgrounds", home()),
        format!("{}/Pictures/Wallpapers", home()),
        "/usr/share/backgrounds/sway".to_string(),
        "/usr/share/backgrounds".to_string(),
    ];
    let exts = ["jpg", "jpeg", "png", "webp", "bmp"];
    let mut found: Vec<String> = Vec::new();
    for dir in dirs {
        let Ok(entries) = std::fs::read_dir(&dir) else { continue };
        for entry in entries.flatten() {
            let p = entry.path();
            let is_match = p
                .extension()
                .and_then(|e| e.to_str())
                .map(|e| exts.contains(&e.to_lowercase().as_str()))
                .unwrap_or(false);
            if is_match {
                if let Some(s) = p.to_str() {
                    found.push(s.to_string());
                }
            }
        }
    }
    found.sort();
    found.dedup();
    found
}

/// Opens a native file picker and copies the chosen image into
/// `~/desktop backgrounds` so it shows up in `scan_wallpapers` from then on.
/// Blocking (GTK dialog) — call via spawn_blocking, same as other slow calls.
pub fn import_wallpaper() -> Option<String> {
    let dest_dir = format!("{}/desktop backgrounds", home());
    let picked = rfd::FileDialog::new()
        .add_filter("Images", &["jpg", "jpeg", "png", "webp", "bmp"])
        .set_directory(&dest_dir)
        .pick_file()?;

    let _ = std::fs::create_dir_all(&dest_dir);
    let file_name = picked.file_name()?.to_str()?.to_string();
    let dest = std::path::Path::new(&dest_dir).join(&file_name);
    if picked != dest {
        std::fs::copy(&picked, &dest).ok()?;
    }
    dest.to_str().map(|s| s.to_string())
}

/// Rewrites the sway config's `output * bg` line for either mode and applies
/// it live via swaymsg — same split as `update_sway_layout`/`reload`.
pub fn apply_wallpaper(config: &Config) {
    let new_line = if config.wallpaper_mode == "color" {
        format!("output * bg {} solid_color", config.wallpaper_color)
    } else if !config.wallpaper_path.is_empty() {
        let fit = if config.wallpaper_fit.is_empty() { "fill" } else { &config.wallpaper_fit };
        format!("output * bg \"{}\" {}", config.wallpaper_path, fit)
    } else {
        return;
    };

    let config_path = format!("{}/.config/sway/config", home());
    let Ok(content) = std::fs::read_to_string(&config_path) else { return };
    let mut lines: Vec<String> = content.lines().map(|l| l.to_string()).collect();
    let mut handled = false;
    for line in &mut lines {
        let t = line.trim_start();
        if t.starts_with("output") && t.contains(" bg ") {
            *line = new_line.clone();
            handled = true;
            break;
        }
    }
    if !handled {
        lines.push(new_line.clone());
    }
    let _ = std::fs::write(&config_path, lines.join("\n") + "\n");

    let _ = Command::new("swaymsg").arg(&new_line).output();
}

// ── Login screen (LightDM) ──────────────────────────────────────────────

/// Reads the wallpaper path out of `output * bg "<path>" fill` in the sway
/// config — that's the single source of truth for the current wallpaper,
/// there's no separate field for it in our own Config.
pub fn get_current_wallpaper() -> Option<String> {
    let config_path = format!("{}/.config/sway/config", home());
    let content = std::fs::read_to_string(config_path).ok()?;
    for line in content.lines() {
        let t = line.trim();
        if t.starts_with("output") && t.contains(" bg ") {
            let start = t.find('"')?;
            let rest = &t[start + 1..];
            let end = rest.find('"')?;
            return Some(rest[..end].to_string());
        }
    }
    None
}

/// LightDM's greeter runs as its own `lightdm` system user, which can't
/// read into our 700 home directory — so the wallpaper has to be copied
/// somewhere world-readable, and the greeter config (root-owned, under
/// /etc) has to be edited to point at it. Both need root, hence the same
/// spawned-terminal-with-sudo pattern as pacman/system-service updates.
pub fn sync_greeter_background(terminal: &str, wallpaper: &str) {
    let term = if terminal.is_empty() { "alacritty" } else { terminal };
    let ext = std::path::Path::new(wallpaper)
        .extension()
        .and_then(|e| e.to_str())
        .unwrap_or("jpg");
    let dest = format!("/usr/share/backgrounds/sway-control/greeter-bg.{ext}");
    let conf = "/etc/lightdm/lightdm-gtk-greeter.conf";
    let script = format!(
        "sudo mkdir -p /usr/share/backgrounds/sway-control && \
         sudo cp \"{wallpaper}\" {dest} && sudo chmod 644 {dest} && \
         if grep -q '^background=' {conf}; then \
             sudo sed -i -E 's|^background=.*|background={dest}|' {conf}; \
         elif grep -q '^#background=' {conf}; then \
             sudo sed -i -E 's|^#background=.*|background={dest}|' {conf}; \
         else \
             echo 'background={dest}' | sudo tee -a {conf} >/dev/null; \
         fi && \
         if grep -q '^user-background=' {conf}; then \
             sudo sed -i -E 's|^user-background=.*|user-background=false|' {conf}; \
         elif grep -q '^#user-background=' {conf}; then \
             sudo sed -i -E 's|^#user-background=.*|user-background=false|' {conf}; \
         else \
             echo 'user-background=false' | sudo tee -a {conf} >/dev/null; \
         fi; \
         echo; read -rsn1 -p 'Press any key to close...'"
    );
    let _ = Command::new(term).arg("-e").arg("bash").arg("-c").arg(script).spawn();
}

#[cfg(test)]
mod nmcli_parsing_tests {
    use super::*;

    #[test]
    fn parses_plain_fields() {
        assert_eq!(
            parse_nmcli_terse_line("yes:MySSID:80:WPA2"),
            vec!["yes", "MySSID", "80", "WPA2"],
        );
    }

    #[test]
    fn unescapes_colon_inside_a_field() {
        // nmcli backslash-escapes literal `:` in field values (e.g. an SSID
        // containing a colon) so it isn't mistaken for a column separator.
        assert_eq!(
            parse_nmcli_terse_line(r"yes:My\:SSID:80:WPA2"),
            vec!["yes", "My:SSID", "80", "WPA2"],
        );
    }

    #[test]
    fn unescapes_backslash_itself() {
        assert_eq!(
            parse_nmcli_terse_line(r"a\\b:c"),
            vec![r"a\b", "c"],
        );
    }

    #[test]
    fn handles_empty_trailing_field() {
        // An open network reports an empty SECURITY column.
        assert_eq!(
            parse_nmcli_terse_line("MySSID::80"),
            vec!["MySSID", "", "80"],
        );
    }
}
