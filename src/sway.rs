// ── Network / Bluetooth ─────────────────────────────────────────────────────
//
// This machine runs systemd-networkd + iwd (no NetworkManager, no nmcli),
// so wifi is driven through `iwctl` and ethernet through `ip`. `iwctl`
// always emits ANSI color codes even when piped, so its output gets
// stripped before parsing.

fn strip_ansi(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut chars = s.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\u{1b}' && chars.peek() == Some(&'[') {
            chars.next();
            for c2 in chars.by_ref() {
                if c2.is_ascii_alphabetic() {
                    break;
                }
            }
        } else {
            out.push(c);
        }
    }
    out
}

/// Splits an already-ANSI-stripped table row on runs of 2+ spaces — iwctl's
/// column padding — while keeping single spaces inside a field (network
/// names like "Narnea Home" or "[oven] Samsung"). A run of exactly one
/// space is only ever a real inter-word space here, never a boundary.
fn split_table_columns(line: &str) -> Vec<String> {
    let mut cols = Vec::new();
    let mut current = String::new();
    let mut pending_spaces = 0u32;
    for c in line.chars() {
        if c == ' ' {
            pending_spaces += 1;
        } else {
            if pending_spaces >= 2 {
                let trimmed = current.trim();
                if !trimmed.is_empty() {
                    cols.push(trimmed.to_string());
                }
                current.clear();
            } else if pending_spaces == 1 && !current.is_empty() {
                current.push(' ');
            }
            pending_spaces = 0;
            current.push(c);
        }
    }
    let trimmed = current.trim();
    if !trimmed.is_empty() {
        cols.push(trimmed.to_string());
    }
    cols
}

/// Same column-boundary logic as `split_table_columns`, but for text that
/// still has its ANSI escape codes — iwctl represents each network's
/// signal strength as always-4 literal `*` characters, using color (dim
/// gray for the "off" bars) to show actual strength rather than the
/// character count. Escape sequences are kept verbatim inside whichever
/// column they fall in (invisible for column-boundary purposes) so
/// `count_active_stars` can later tell dim stars from bright ones.
fn split_table_columns_raw(line: &str) -> Vec<String> {
    let mut cols = Vec::new();
    let mut current = String::new();
    let mut pending_spaces = 0u32;
    let mut chars = line.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\u{1b}' && chars.peek() == Some(&'[') {
            current.push(c);
            current.push(chars.next().unwrap());
            for c2 in chars.by_ref() {
                current.push(c2);
                if c2.is_ascii_alphabetic() {
                    break;
                }
            }
            continue;
        }
        if c == ' ' {
            pending_spaces += 1;
        } else {
            if pending_spaces >= 2 {
                if !strip_ansi(&current).trim().is_empty() {
                    cols.push(std::mem::take(&mut current));
                } else {
                    current.clear();
                }
            } else if pending_spaces == 1 && !current.is_empty() {
                current.push(' ');
            }
            pending_spaces = 0;
            current.push(c);
        }
    }
    if !strip_ansi(&current).trim().is_empty() {
        cols.push(current);
    }
    cols
}

/// Counts `*` characters that aren't wrapped in iwctl's dim-gray escape
/// (`\x1b[1;90m` ... `\x1b[0m`) — the visual "filled" signal bars.
fn count_active_stars(raw: &str) -> u8 {
    let mut active = 0u8;
    let mut dimmed = false;
    let mut chars = raw.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\u{1b}' && chars.peek() == Some(&'[') {
            let mut seq = String::new();
            chars.next();
            for c2 in chars.by_ref() {
                seq.push(c2);
                if c2.is_ascii_alphabetic() {
                    break;
                }
            }
            if seq.starts_with("1;90") {
                dimmed = true;
            } else if seq.starts_with('0') {
                dimmed = false;
            }
        } else if c == '*' && !dimmed {
            active += 1;
        }
    }
    active
}

