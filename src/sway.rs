#[derive(Debug, Clone)]
pub struct WifiNetwork {
    pub ssid: String,
    pub security: String,
    pub signal_bars: u8,
    pub known: bool,
}

pub fn get_wifi_networks() -> Vec<WifiNetwork> {
    match detect_network_backend() {
        NetworkBackend::NetworkManager => get_wifi_networks_nm(),
        NetworkBackend::Iwd => get_wifi_networks_iwd(),
        NetworkBackend::None => Vec::new(),
    }
}

fn get_wifi_networks_nm() -> Vec<WifiNetwork> {
    let known_out = run_output("nmcli", &["-t", "-f", "NAME", "connection", "show"]);
    let known: Vec<String> = known_out.lines().map(str::to_string).collect();

    let out = run_output("nmcli", &["-t", "-f", "SSID,SECURITY,SIGNAL", "device", "wifi", "list"]);
    let mut networks = Vec::new();
    for line in out.lines() {
        let cols = parse_nmcli_terse_line(line);
        if cols.len() < 3 {
            continue;
        }
        let ssid = cols[0].trim().to_string();
        if ssid.is_empty() {
            continue;
        }
        let security = cols[1].trim().to_string();
        let signal: u8 = cols[2].trim().parse().unwrap_or(0);
        let signal_bars = ((signal as f32 / 100.0) * 4.0).round().min(4.0) as u8;
        let known = known.iter().any(|k| k == &ssid);
        networks.push(WifiNetwork { ssid, security, signal_bars, known });
    }
    networks
}

fn get_wifi_networks_iwd() -> Vec<WifiNetwork> {
    let Some(iface) = wifi_iface() else { return Vec::new() };
    let known_out = strip_ansi(&run_output("iwctl", &["known-networks", "list"]));
    let known: Vec<String> = known_out.lines()
        .skip_while(|l| !l.contains("Last connected"))
        .skip(1)
        .filter_map(|l| split_table_columns(l).into_iter().next())
        .collect();

    let out = run_output("iwctl", &["station", &iface, "get-networks"]);
    let mut networks = Vec::new();
    for line in out.lines() {
        let cols = split_table_columns_raw(line);
        if cols.len() < 3 {
            continue;
        }
        let ssid = strip_ansi(&cols[0]).trim().to_string();
        let security = strip_ansi(&cols[1]).trim().to_string();
        if ssid.is_empty() || ssid == "Network name" {
            continue;
        }
        let signal_bars = count_active_stars(&cols[2]);
        let known = known.iter().any(|k| k == &ssid);
        networks.push(WifiNetwork { ssid, security, signal_bars, known });
    }
    networks
}

